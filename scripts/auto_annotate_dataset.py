"""Generate provisional labels, captions, and VQA answers for every image."""
from __future__ import annotations

import argparse
import json
import sys
import zipfile
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))

QUESTIONS = [
    ("object", "What is a prominent object or subject in the image?"),
    ("scene", "What kind of scene is shown?"),
    ("visual_detail", "What other visible object or feature appears in the scene?"),
]
LABELS = ["door", "lamp", "photo frame", "wardrobe", "window"]


def source_label(archive: zipfile.ZipFile, entries: list[zipfile.ZipInfo], index: int, root: Path) -> str:
    parts = entries[index].filename.split("/")
    split, filename = parts[1], Path(parts[2]).stem
    label_path = root / "source" / "extracted" / "labels" / split / f"{filename}.txt"
    if not label_path.exists():
        return "unknown"
    ids = []
    for line in label_path.read_text(encoding="utf-8").splitlines():
        if line.strip():
            ids.append(int(line.split()[0]))
    return LABELS[ids[0]] if ids and 0 <= ids[0] < len(LABELS) else "unknown"


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--manifest", default="dataset/annotations_300.json")
    parser.add_argument("--archive", default="dataset/source/HomeObjects-3K_5class_143_per_class.zip")
    parser.add_argument("--batch-size", type=int, default=4)
    parser.add_argument("--output", default="dataset/annotations_300.json")
    args = parser.parse_args()

    from PIL import Image
    import torch
    from transformers import BlipForConditionalGeneration, BlipForQuestionAnswering, BlipProcessor

    root = Path(__file__).resolve().parents[1]
    data = json.loads((root / args.manifest).read_text(encoding="utf-8-sig"))
    items = data["items"]
    processor = BlipProcessor.from_pretrained("Salesforce/blip-image-captioning-base")
    caption_model = BlipForConditionalGeneration.from_pretrained("Salesforce/blip-image-captioning-base").eval()
    vqa_processor = BlipProcessor.from_pretrained("Salesforce/blip-vqa-base")
    vqa_model = BlipForQuestionAnswering.from_pretrained("Salesforce/blip-vqa-base").eval()
    archive = zipfile.ZipFile(root / args.archive)
    entries = [x for x in archive.infolist() if x.filename.lower().endswith((".jpg", ".jpeg", ".png")) and x.filename.startswith("images/")]

    for start in range(0, len(items), args.batch_size):
        batch = items[start:start + args.batch_size]
        images = [Image.open(root / "dataset" / item["image_path"]).convert("RGB") for item in batch]
        caption_inputs = processor(images=images, return_tensors="pt", padding=True)
        with torch.inference_mode():
            captions = caption_model.generate(**caption_inputs, max_new_tokens=30, num_beams=3)
        caption_text = [processor.decode(row, skip_special_tokens=True).strip() for row in captions]

        repeated_images = [image for image in images for _ in QUESTIONS]
        questions = [question for _ in images for _, question in QUESTIONS]
        vqa_inputs = vqa_processor(images=repeated_images, text=questions, return_tensors="pt", padding=True)
        with torch.inference_mode():
            answers = vqa_model.generate(**vqa_inputs, max_new_tokens=20, num_beams=3)
        answer_text = [vqa_processor.decode(row, skip_special_tokens=True).strip() for row in answers]

        for offset, item in enumerate(batch):
            item["source_label"] = source_label(archive, entries, int(item["source_index"]), root)
            item["caption"] = caption_text[offset]
            item["qa_pairs"] = []
            for q_index, (qa_type, question) in enumerate(QUESTIONS):
                item["qa_pairs"].append({"type": qa_type, "question": question, "answer": answer_text[offset * len(QUESTIONS) + q_index]})
            item["status"] = "auto_generated_needs_review"
            item["annotation_note"] = "Generated by BLIP from restored images; review before ground-truth use."
        print(f"annotated {min(start + len(batch), len(items))}/{len(items)}", flush=True)

    archive.close()
    data["annotation_status"] = "auto_generated_draft"
    data["annotation_notes"] = "Labels, captions, and 3 QA pairs generated by BLIP. Human verification required."
    data["source"] = "restored_image_folder_and_blip"
    output = root / args.output
    temp = output.with_suffix(".tmp.json")
    temp.write_text(json.dumps(data, indent=2, ensure_ascii=False), encoding="utf-8")
    temp.replace(output)
    print(f"Wrote {output}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
